#!/usr/bin/env python3
"""Generate the docs site's reference pages from the code.

Writes two Markdown pages that would otherwise drift from the source:

- ``docs/reference/configuration.md``: every ``Settings`` field (name, type,
  default, ``LOGIC_LOOM_*`` env var, description), read from
  ``logic_loom_api.config.Settings``.
- ``docs/reference/http-api.md``: every ``/api/*`` operation (method, path,
  summary), read from the sidecar's OpenAPI schema.

The docs workflow runs this before ``mkdocs build`` so the published site
always matches the tagged code. The committed copies are a convenience for
reading the docs on GitHub; regenerate them with:

    uv sync --all-packages --all-extras --group docs
    uv run python scripts/gen_docs_reference.py

Routers that need an optional extra are mounted with try/except in
``main.py``. Install every extra (as above) so the API page lists them all;
the script prints which route groups it found.
"""

from __future__ import annotations

import os
import sys
import tempfile
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"

GENERATED_NOTE = (
    "<!-- Generated by scripts/gen_docs_reference.py. Do not edit by hand. -->\n\n"
)


def _isolate_from_user_config() -> None:
    """Point every settings source at an empty tmp dir.

    The output must not depend on the machine that runs the script: no user
    config.toml, no LOGIC_LOOM_* overrides, no real workspace.
    """
    tmp = Path(tempfile.mkdtemp(prefix="ll-docs-"))
    for key in list(os.environ):
        if key.startswith("LOGIC_LOOM_"):
            del os.environ[key]
    os.environ["LOGIC_LOOM_CONFIG"] = str(tmp / "missing-config.toml")
    os.environ["LOGIC_LOOM_AKMS_WORKSPACE"] = str(tmp / "akms-workspace")
    os.environ["LOGIC_LOOM_CACHE_PATH"] = str(tmp / "cache")
    os.environ["HOME"] = str(tmp / "home")


def _type_name(annotation: Any) -> str:
    text = getattr(annotation, "__name__", None) if isinstance(annotation, type) else None
    if text is None:
        text = str(annotation)
    for noise in ("typing.", "pathlib.", "logic_loom_api.config."):
        text = text.replace(noise, "")
    return text.replace("NoneType", "None")


def _default(field: Any) -> str:
    if field.default_factory is not None:
        return "computed"
    value = field.default
    if value is None:
        return "unset"
    if isinstance(value, str):
        return f'`"{value}"`'
    return f"`{value}`"


def _cell(text: str) -> str:
    text = " ".join(text.split()).replace("|", "\\|")
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def configuration_page() -> str:
    from logic_loom_api.config import Settings

    prefix = Settings.model_config.get("env_prefix", "LOGIC_LOOM_")
    lines = [
        "# Configuration reference",
        "",
        GENERATED_NOTE.rstrip(),
        "",
        "Every setting Logic-Loom reads, in the order the code declares them. Set them in",
        "`~/.config/logic-loom/config.toml` (or the file named by `LOGIC_LOOM_CONFIG`), or",
        f"override one with its `{prefix}*` environment variable. Precedence and examples are",
        "in [Configuration](../install/configuration.md).",
        "",
        "| Key | Type | Default | Env var | Description |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, field in Settings.model_fields.items():
        lines.append(
            f"| `{name}` | `{_cell(_type_name(field.annotation))}` | {_default(field)} "
            f"| `{prefix}{name.upper()}` | {_cell(field.description or '')} |"
        )
    lines.append("")
    return "\n".join(lines)


def http_api_page() -> tuple[str, list[str]]:
    from logic_loom_api.main import api

    schema = api.openapi()
    groups: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for path, ops in schema.get("paths", {}).items():
        if not path.startswith("/api/"):
            continue
        group = "/".join(path.split("/")[:3])
        for method, op in ops.items():
            if method.upper() not in {"GET", "POST", "PUT", "PATCH", "DELETE"}:
                continue
            summary = op.get("summary") or op.get("operationId") or ""
            groups[group].append((method.upper(), path, summary))

    version = schema.get("info", {}).get("version", "")
    lines = [
        "# HTTP API reference",
        "",
        GENERATED_NOTE.rstrip(),
        "",
        "The desktop shell talks to the `logic-loom-api` sidecar over these routes. The",
        "port is random per launch (see [Architecture](../developers/architecture.md)),",
        "and a running sidecar also serves the full interactive schema at `/docs`.",
        "Route groups that need an optional extra appear only when it is installed. The",
        "AKMS batch picker is a mounted sub-app at `/api/picker` with its own schema, so",
        "its routes are not listed here; see the",
        "[AKMS batch picker HTTP API](https://cemm2.github.io/AKMS/reference/nodes-gen/batch-picker/api-reference.html).",
        "",
    ]
    if version:
        lines += [f"Generated from API version `{version}`.", ""]
    for group in sorted(groups):
        lines += [f"## `{group}`", "", "| Method | Path | Summary |", "| --- | --- | --- |"]
        for method, path, summary in sorted(groups[group], key=lambda r: (r[1], r[0])):
            lines.append(f"| `{method}` | `{path}` | {_cell(summary)} |")
        lines.append("")
    return "\n".join(lines), sorted(groups)


def main() -> int:
    _isolate_from_user_config()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "configuration.md").write_text(configuration_page(), encoding="utf-8")
    api, groups = http_api_page()
    (OUT / "http-api.md").write_text(api, encoding="utf-8")
    print(f"wrote {OUT / 'configuration.md'}")
    print(f"wrote {OUT / 'http-api.md'} ({len(groups)} route groups: {', '.join(groups)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
